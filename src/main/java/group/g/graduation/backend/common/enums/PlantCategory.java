package group.g.graduation.backend.common.enums;

/**
 * Plant category - تصنيف النباتات الشعبية الفلسطينية والأعشاب
 * Palestinian folk plants and herbs categories
 */
public enum PlantCategory {

    // ===== تصنيف عام (للتوافق مع بيانات قديمة) =====
    HERBS,                  // أعشاب (تصنيف عام/قديم - يُستخدم فقط للبيانات القديمة)

    // ===== الأعشاب الطبية والعطرية =====
    MEDICINAL_HERBS,        // أعشاب طبية (زعتر، ميرمية، بابونج، إكليل الجبل)
    AROMATIC_HERBS,         // أعشاب عطرية (نعناع، ريحان، لافندر، ياسمين)

    // ===== النباتات الشعبية الفلسطينية =====
    TRADITIONAL_PLANTS,     // نباتات تراثية فلسطينية (قيصوم، لوف، خبيزة، سلق بري)
    WILD_PLANTS,            // نباتات برية (حميض، عكوب، زعمطوط، لسان الثور)

    // ===== نباتات الزينة =====
    ORNAMENTAL_FLOWERS,     // أزهار زينة (جهنمية، ورد، كركديه)
    ORNAMENTAL_SHRUBS,      // شجيرات زينة (ياسمين، فل، مسك الليل)

    // ===== نباتات أخرى =====
    SUCCULENTS,             // صبار ونباتات عصارية (صبار، ألوفيرا)
    OTHER                   // أخرى
}
